//! sc-18765 — **LTX-2.5 conv video VAE + audio VAE conformance against the shipped 2.3 ports.**
//!
//! Epic 18755 §1.2 claims LTX-2.5's `vae/ltx-2.5-video-vae-conv-bf16` and `vae/ltx-2.5-audio-vae-bf16`
//! are "drop-in reuse" for the ports this crate already ships. "Drop-in" is a claim about **names,
//! shapes and layout**, and nothing in the engine would notice if upstream quietly changed one: a
//! renamed block would surface as a missing-key error at render time on a 42 GB pipeline, and a
//! re-laid-out conv would surface as *plausible garbage*. So the claim is asserted here, key by key,
//! against a committed key-set fixture
//! (`docs/reference/sc-18765-vae-keysets/ltx-vae-keysets.json`, regenerated by
//! `crates/media/mlx-gen/tools/dump_ltx_vae_keysets.py`).
//!
//! These tests need **no weights and no GPU** — the fixture carries the recorded key/shape lists —
//! so they run in ordinary CI. The real-weight round trip lives in `ltx_2_5_vae_real_weights.rs`.
//!
//! ## The structural differences that are real (documented, not absorbed)
//!
//! | | LTX-2.3 all-in-one | LTX-2.5 component file |
//! |---|---|---|
//! | video VAE tensor namespace | `vae.decoder.*` / `vae.encoder.*` | `decoder.*` / `encoder.*` (file root) |
//! | per-channel stats | `vae.per_channel_statistics.{mean,std}-of-means` | same names, at the root |
//! | audio VAE / vocoder namespace | `audio_vae.*` / `vocoder.*` | **identical** |
//! | conv layout on disk | PyTorch (upstream), channels-last in the `ltx-2.3-mlx` rehost | PyTorch |
//! | `latent_log_var` | absent (⇒ `uniform`) | `uniform` (conv) / `constant` (DiffVAE encoder) |
//!
//! Everything else — block lists, `patch_size`, `latent_channels`, `norm_layer`,
//! `spatial_padding_mode`, `timestep_conditioning`, every audio-VAE and vocoder config value, and
//! every tensor name below the namespace — is byte-for-byte the same, which is what makes the reuse
//! legitimate rather than convenient.

