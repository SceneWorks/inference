/// The DiffVAE (`CausalDiffusionVAE`) reuses the conv VAE's **encoder module verbatim** — same
/// tensor names, same shapes, right down to the 129-channel `conv_out` head — and differs only in
/// the declared `latent_log_var`. That is the whole reason a conv-VAE-only 2.5 build is viable.
#[test]
fn diffvae_encoder_is_the_conv_encoder_with_only_the_logvar_mode_changed() {
    let fx = fixture();
    let conv = tensors(&fx, "ltx_2_5_video_vae_conv");
    let diff = tensors(&fx, "ltx_2_5_video_vae_diffusion");
    let conv_enc: BTreeMap<_, _> = conv
        .iter()
        .filter(|(k, _)| k.starts_with("encoder.") || k.starts_with("per_channel_statistics."))
        .map(|(k, v)| (k.clone(), v.clone()))
        .collect();
    assert_eq!(
        conv_enc, diff,
        "the DiffVAE's encoder is no longer tensor-identical to the conv VAE's"
    );
    assert_eq!(
        conv_enc["encoder.conv_out.conv.weight"],
        vec![129, 1024, 3, 3, 3],
        "both modes emit latent_channels + 1 = 129 conv_out channels"
    );

    let diff_cfg = config_of(&fx, "ltx_2_5_video_vae_diffusion");
    let diff_vae = diff_cfg.get("vae").expect("config.vae");
    let parsed =
        LtxVaeConfig::from_embedded_vae(diff_vae).expect("parse the nested DiffVAE config");
    assert_eq!(parsed.latent_log_var, LatentLogVar::Constant);
    assert_eq!(parsed.latent_channels, 128, "nested `encoder.out_channels`");
    assert_eq!(parsed.patch_size, 4);
    assert_eq!(
        parsed.encoder_blocks,
        LtxVaeConfig::defaults().encoder_blocks,
        "the DiffVAE encoder's `blocks` list diverged from the conv encoder's"
    );
    assert_eq!(
        diff_vae
            .pointer("/decoder/_class_name")
            .and_then(serde_json::Value::as_str),
        Some("NADiffusionDecoder"),
        "the DiffVAE decoder is a different architecture (sc-18766 / sc-18767), not this port's"
    );
    // Recorded but unused: the reference's CONSTANT branch fills the log-variance with a hardcoded
    // `approx_ln_0 = -30`, never with this value. Asserted so a future upstream change that starts
    // honouring it cannot pass unnoticed.
    assert_eq!(
        diff_vae
            .pointer("/encoder/latent_log_var_value")
            .and_then(serde_json::Value::as_f64),
        Some(-7.824046010856292)
    );
}

/// Both log-variance widths are declared, and a mode that disagrees with the checkpoint's
/// `conv_out` width is a load error rather than a silently mis-sliced latent.
#[test]
fn latent_log_var_modes_declare_their_conv_out_widths() {
    assert_eq!(LatentLogVar::Uniform.conv_out_channels(128), 129);
    assert_eq!(LatentLogVar::Constant.conv_out_channels(128), 129);
    assert_eq!(LatentLogVar::PerChannel.conv_out_channels(128), 256);
    assert_eq!(LatentLogVar::None.conv_out_channels(128), 128);
    assert!(LatentLogVar::parse("gaussian").is_err());
    for (s, want) in [
        ("uniform", LatentLogVar::Uniform),
        ("constant", LatentLogVar::Constant),
        ("per_channel", LatentLogVar::PerChannel),
        ("none", LatentLogVar::None),
    ] {
        assert_eq!(LatentLogVar::parse(s).unwrap(), want);
    }
}

