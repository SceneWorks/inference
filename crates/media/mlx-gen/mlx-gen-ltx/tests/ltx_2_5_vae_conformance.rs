const KEYSETS: &str = concat!(
    env!("CARGO_MANIFEST_DIR"),
    "/../../../../docs/reference/sc-18765-vae-keysets/ltx-vae-keysets.json"
);

// ---------------------------------------------------------------------------------------------
// Fixture access
// ---------------------------------------------------------------------------------------------

fn fixture() -> serde_json::Value {
    let text = std::fs::read_to_string(KEYSETS).unwrap_or_else(|e| {
        panic!("read {KEYSETS}: {e} (regenerate with tools/dump_ltx_vae_keysets.py)")
    });
    serde_json::from_str(&text).expect("parse ltx-vae-keysets.json")
}

fn component(fixture: &serde_json::Value, name: &str) -> serde_json::Value {
    fixture
        .get("components")
        .and_then(|c| c.get(name))
        .unwrap_or_else(|| panic!("fixture component {name} missing"))
        .clone()
}

/// `{tensor name -> shape}` for one fixture component.
fn tensors(fixture: &serde_json::Value, name: &str) -> BTreeMap<String, Vec<i32>> {
    component(fixture, name)
        .get("tensors")
        .and_then(serde_json::Value::as_object)
        .unwrap_or_else(|| panic!("fixture component {name} has no tensors"))
        .iter()
        .map(|(k, v)| {
            let shape = v
                .as_array()
                .expect("shape array")
                .iter()
                .map(|d| d.as_i64().expect("shape dim") as i32)
                .collect();
            (k.clone(), shape)
        })
        .collect()
}

fn config_of(fixture: &serde_json::Value, name: &str) -> serde_json::Value {
    component(fixture, name)
        .get("config")
        .unwrap_or_else(|| panic!("fixture component {name} has no config"))
        .clone()
}

/// Report a set difference as a sorted, readable list (empty ⇒ `[]`).
fn missing(from: &BTreeMap<String, Vec<i32>>, against: &BTreeMap<String, Vec<i32>>) -> Vec<String> {
    from.keys()
        .filter(|k| !against.contains_key(*k))
        .cloned()
        .collect()
}

// ---------------------------------------------------------------------------------------------
// 1. Key names: the 2.5 component files carry exactly the 2.3 components' tensors
// ---------------------------------------------------------------------------------------------

/// The 2.3 split-MLX key a 2.5 conv-VAE key maps to, per half — the mapping
/// `convert::sanitize_vae_{decoder,encoder}` implements. `None` ⇒ the key belongs to the other half.
fn video_key_for_half(key: &str, half: &str) -> Option<String> {
    match key {
        "per_channel_statistics.mean-of-means" => Some(if half == "decoder" {
            "per_channel_statistics.mean".into()
        } else {
            "per_channel_statistics._mean_of_means".into()
        }),
        "per_channel_statistics.std-of-means" => Some(if half == "decoder" {
            "per_channel_statistics.std".into()
        } else {
            "per_channel_statistics._std_of_means".into()
        }),
        _ => key.strip_prefix(&format!("{half}.")).map(str::to_string),
    }
}

#[test]
fn conv_vae_component_carries_exactly_the_2_3_split_key_sets() {
    let fx = fixture();
    let conv = tensors(&fx, "ltx_2_5_video_vae_conv");
    for (half, component_name) in [
        ("decoder", "ltx_2_3_mlx_vae_decoder"),
        ("encoder", "ltx_2_3_mlx_vae_encoder"),
    ] {
        let want = tensors(&fx, component_name);
        let got: BTreeMap<String, Vec<i32>> = conv
            .iter()
            .filter_map(|(k, v)| video_key_for_half(k, half).map(|nk| (nk, v.clone())))
            .collect();
        assert_eq!(
            missing(&got, &want),
            Vec::<String>::new(),
            "LTX-2.5 {half} tensors absent from the shipped 2.3 {component_name} port"
        );
        assert_eq!(
            missing(&want, &got),
            Vec::<String>::new(),
            "shipped 2.3 {component_name} tensors absent from the LTX-2.5 {half}"
        );
        assert_eq!(
            got.len(),
            want.len(),
            "{half}: 2.5 supplies {} tensors, the 2.3 port consumes {}",
            got.len(),
            want.len()
        );
    }
}

/// The 2.3 split-MLX key a 2.5 audio-VAE key maps to (`convert::sanitize_audio_vae` /
/// `sanitize_vocoder`), and which component it lands in.
fn audio_key(key: &str) -> Option<(&'static str, String)> {
    if let Some(rest) = key.strip_prefix("audio_vae.decoder.") {
        return Some(("audio_vae", rest.to_string()));
    }
    if let Some(stat) = key.strip_prefix("audio_vae.per_channel_statistics.") {
        return match stat {
            "mean-of-means" => Some(("audio_vae", "per_channel_statistics._mean_of_means".into())),
            "std-of-means" => Some(("audio_vae", "per_channel_statistics._std_of_means".into())),
            _ => None,
        };
    }
    if key.starts_with("vocoder.") {
        // The reference strips EVERY `vocoder.` occurrence, not just the leading one.
        return Some(("vocoder", key.replace("vocoder.", "")));
    }
    None
}

#[test]
fn audio_vae_and_vocoder_components_carry_exactly_the_2_3_key_sets() {
    let fx = fixture();
    let audio = tensors(&fx, "ltx_2_5_audio_vae");
    let mut mapped: HashMap<&str, BTreeMap<String, Vec<i32>>> = HashMap::new();
    let mut unmapped: Vec<&String> = Vec::new();
    for (k, v) in &audio {
        match audio_key(k) {
            Some((component, nk)) => {
                mapped.entry(component).or_default().insert(nk, v.clone());
            }
            // The 2.3 audio path drops the audio VAE's ENCODER (the pipeline only ever decodes),
            // so those keys are expected to be unconsumed — see the assertion below.
            None => unmapped.push(k),
        }
    }
    assert!(
        unmapped.iter().all(|k| k.starts_with("audio_vae.encoder.")),
        "LTX-2.5 audio VAE carries tensors the 2.3 mapping does not recognise: {:?}",
        unmapped
            .iter()
            .filter(|k| !k.starts_with("audio_vae.encoder."))
            .collect::<Vec<_>>()
    );
    assert_eq!(
        unmapped.len(),
        44,
        "the audio VAE encoder is 44 tensors in both 2.3 and 2.5; a change here means the audio \
         encoder was restructured"
    );

    for (component, fixture_name) in [
        ("audio_vae", "ltx_2_3_mlx_audio_vae"),
        ("vocoder", "ltx_2_3_mlx_vocoder"),
    ] {
        let want = tensors(&fx, fixture_name);
        let got = mapped.remove(component).unwrap_or_default();
        assert_eq!(
            missing(&got, &want),
            Vec::<String>::new(),
            "LTX-2.5 {component} tensors absent from the shipped 2.3 port"
        );
        assert_eq!(
            missing(&want, &got),
            Vec::<String>::new(),
            "shipped 2.3 {component} tensors absent from LTX-2.5"
        );
    }
}

// ---------------------------------------------------------------------------------------------
// 2. Layout: the recorded 2.5 shapes are the PyTorch pre-image of the shipped channels-last ones
// ---------------------------------------------------------------------------------------------

fn permute(shape: &[i32], axes: &[usize]) -> Vec<i32> {
    axes.iter().map(|&a| shape[a]).collect()
}

/// The channels-last shape `convert::conv_channels_last` produces for a video/audio VAE tensor:
/// Conv3d `[O,I,D,H,W] -> [O,D,H,W,I]`, Conv2d `[O,I,H,W] -> [O,H,W,I]`, gated on `conv`+`weight`.
fn vae_channels_last(key: &str, shape: &[i32]) -> Vec<i32> {
    if !(key.to_ascii_lowercase().contains("conv") && key.contains("weight")) {
        return shape.to_vec();
    }
    match shape.len() {
        5 => permute(shape, &[0, 2, 3, 4, 1]),
        4 => permute(shape, &[0, 2, 3, 1]),
        _ => shape.to_vec(),
    }
}

/// `convert::sanitize_vocoder`'s rank-3 transposes, gated on `weight` (NOT on `conv`):
/// `ups` ConvTranspose1d `[I,O,K] -> [O,K,I]`, every other Conv1d `[O,I,K] -> [O,K,I]`.
fn vocoder_channels_last(key: &str, shape: &[i32]) -> Vec<i32> {
    if key.contains("weight") && shape.len() == 3 {
        if key.contains("ups") {
            permute(shape, &[1, 2, 0])
        } else {
            permute(shape, &[0, 2, 1])
        }
    } else {
        shape.to_vec()
    }
}

#[test]
fn recorded_2_5_shapes_are_the_pytorch_preimage_of_the_shipped_channels_last_shapes() {
    let fx = fixture();
    let conv = tensors(&fx, "ltx_2_5_video_vae_conv");
    let mut checked = 0usize;
    for (half, fixture_name) in [
        ("decoder", "ltx_2_3_mlx_vae_decoder"),
        ("encoder", "ltx_2_3_mlx_vae_encoder"),
    ] {
        let want = tensors(&fx, fixture_name);
        for (k, shape) in &conv {
            let Some(nk) = video_key_for_half(k, half) else {
                continue;
            };
            let expected = &want[&nk];
            assert_eq!(
                &vae_channels_last(&nk, shape),
                expected,
                "{half} {nk}: LTX-2.5 stores {shape:?}, which does not transpose to the shipped \
                 {expected:?}"
            );
            checked += 1;
        }
    }

    let audio = tensors(&fx, "ltx_2_5_audio_vae");
    let want_audio = tensors(&fx, "ltx_2_3_mlx_audio_vae");
    let want_voc = tensors(&fx, "ltx_2_3_mlx_vocoder");
    for (k, shape) in &audio {
        match audio_key(k) {
            Some(("audio_vae", nk)) => {
                assert_eq!(
                    &vae_channels_last(&nk, shape),
                    &want_audio[&nk],
                    "audio {nk}"
                );
                checked += 1;
            }
            Some(("vocoder", nk)) => {
                assert_eq!(
                    &vocoder_channels_last(&nk, shape),
                    &want_voc[&nk],
                    "vocoder {nk}"
                );
                checked += 1;
            }
            _ => {}
        }
    }
    // Guard the loop itself: a mapping helper that silently returned `None` everywhere would make
    // every assertion above vacuous.
    assert_eq!(
        checked,
        86 + 86 + 58 + 1227,
        "expected every shipped 2.3 tensor to be shape-checked against its 2.5 source"
    );
}

