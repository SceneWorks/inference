const HIDDEN: i32 = 32;
const VOCAB: i32 = 48;
const HEAD_DIM: i32 = 8;
const LAYERS: usize = 2;
const HEADS: i32 = 4;
const KV: i32 = 2;
const INTER: i32 = 64;

/// The prompt every case prefills, then two cached decode steps at fixed token ids. Fixed rather
/// than sampled so the golden depends only on the decoder, never on a sampler.
const PROMPT: [i32; 5] = [1, 2, 3, 4, 5];
const DECODE_STEPS: [i32; 2] = [6, 7];

fn golden_path() -> std::path::PathBuf {
    std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("../testdata/architectures/forward_mlx.json")
}

/// Small deterministic `[out, in]` weight. Identical draw sequence on both branches, so the built
/// model is the same model.
fn randn(shape: &[i32], rng: &mut SplitMix64) -> Array {
    let n: i32 = shape.iter().product();
    let data: Vec<f32> = (0..n).map(|_| (rng.next_f32() - 0.5) * 0.4).collect();
    Array::from_slice(&data, shape)
}

fn ones(d: i32) -> Array {
    Array::ones::<f32>(&[d]).unwrap()
}

fn dense_mlp(m: &mut HashMap<String, Array>, p: &dyn Fn(&str) -> String, rng: &mut SplitMix64) {
    m.insert(p("mlp.gate_proj.weight"), randn(&[INTER, HIDDEN], rng));
    m.insert(p("mlp.up_proj.weight"), randn(&[INTER, HIDDEN], rng));
    m.insert(p("mlp.down_proj.weight"), randn(&[HIDDEN, INTER], rng));
}

fn gqa_proj(
    m: &mut HashMap<String, Array>,
    p: &dyn Fn(&str) -> String,
    rng: &mut SplitMix64,
    bias: bool,
) {
    let (qd, kvd) = (HEADS * HEAD_DIM, KV * HEAD_DIM);
    m.insert(p("self_attn.q_proj.weight"), randn(&[qd, HIDDEN], rng));
    m.insert(p("self_attn.k_proj.weight"), randn(&[kvd, HIDDEN], rng));
    m.insert(p("self_attn.v_proj.weight"), randn(&[kvd, HIDDEN], rng));
    m.insert(p("self_attn.o_proj.weight"), randn(&[HIDDEN, qd], rng));
    if bias {
        m.insert(p("self_attn.q_proj.bias"), randn(&[qd], rng));
        m.insert(p("self_attn.k_proj.bias"), randn(&[kvd], rng));
        m.insert(p("self_attn.v_proj.bias"), randn(&[kvd], rng));
    }
}

/// One architecture's config plus the weight map that fits it.
struct Case {
    name: &'static str,
    family: &'static str,
    config: Value,
    weights: HashMap<String, Array>,
    /// Whether this architecture's logits are compared against the golden.
    ///
    /// `false` for the two architectures `sdpa_capped` routes to `sdpa_eager` (Gemma-2's attention
    /// soft-cap, DeepSeek-V2's mismatched MLA q/v head dims). Their forward still runs and is
    /// checked for shape and finiteness; their numerics are pinned bit-for-bit by the candle mirror
    /// instead. See the precision contract at the top of this file.
    numerics_pinned: bool,
}

fn llama() -> Case {
    let mut rng = SplitMix64::new(0x1876_9001);
    let mut m = HashMap::new();
    m.insert(
        "model.embed_tokens.weight".into(),
        randn(&[VOCAB, HIDDEN], &mut rng),
    );
    m.insert("model.norm.weight".into(), ones(HIDDEN));
    m.insert("lm_head.weight".into(), randn(&[VOCAB, HIDDEN], &mut rng));
    for i in 0..LAYERS {
        let p = |s: &str| format!("model.layers.{i}.{s}");
        m.insert(p("input_layernorm.weight"), ones(HIDDEN));
        m.insert(p("post_attention_layernorm.weight"), ones(HIDDEN));
        gqa_proj(&mut m, &p, &mut rng, false);
        dense_mlp(&mut m, &p, &mut rng);
    }
    Case {
        name: "llama",
        family: "llama",
        numerics_pinned: true,
        config: json!({
            "architectures": ["LlamaForCausalLM"], "model_type": "llama",
            "hidden_size": HIDDEN, "intermediate_size": INTER, "num_hidden_layers": LAYERS,
            "num_attention_heads": HEADS, "num_key_value_heads": KV, "head_dim": HEAD_DIM,
            "vocab_size": VOCAB, "rms_norm_eps": 1e-5, "rope_theta": 500000.0,
            "tie_word_embeddings": false,
            "rope_scaling": { "rope_type": "llama3", "factor": 8.0, "low_freq_factor": 1.0,
                "high_freq_factor": 4.0, "original_max_position_embeddings": 64 }
        }),
        weights: m,
    }
}

