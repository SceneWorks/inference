/// Every architecture the shared [`ModelConfig`] serves through the generic decoder.
///
/// Qwen3.6 (`qwen3_5`) is absent on purpose: `ModelConfig::from_json` declines it, and it is served
/// by its own `Qwen35Config`/`Qwen35Model`. Gemma 4 is absent because its decoder does not exist yet
/// (sc-18760); when it does, it belongs here.
fn cases() -> Vec<Case> {
    vec![
        llama(),
        qwen3(),
        phi3(),
        qwen2_moe(),
        gemma2(),
        glm4(),
        deepseek_v2(),
        qwen3_vl(),
    ]
}

/// Prefill `PROMPT`, then run `DECODE_STEPS` cached decode steps, concatenating every logit vector
/// the model produced. Exercises the whole decoder loop — projections, RoPE, attention, KV cache
/// growth, norms, FFN (dense / MoE / MLA), and the LM head — not just a shape.
fn run_forward(case: &Case) -> Vec<f32> {
    let cfg = ModelConfig::from_json(&case.config)
        .unwrap_or_else(|e| panic!("{}: config must parse: {e}", case.name));
    assert_eq!(
        cfg.architecture.family(),
        case.family,
        "{}: family dispatch",
        case.name
    );
    let weights = Weights::from_map(case.weights.clone());
    let model = CausalLm::from_weights(&weights, "", cfg)
        .unwrap_or_else(|e| panic!("{}: model must build: {e}", case.name));

    let mut cache = model.new_cache();
    let mut out = Vec::new();
    let logits = model
        .decode_logits(&input_ids(&PROMPT), &mut cache, 0)
        .unwrap_or_else(|e| panic!("{}: prefill: {e}", case.name));
    out.extend(host(&logits));
    for (step, tok) in DECODE_STEPS.iter().enumerate() {
        let offset = PROMPT.len() as i32 + step as i32;
        let logits = model
            .decode_logits(&input_ids(&[*tok]), &mut cache, offset)
            .unwrap_or_else(|e| panic!("{}: decode {step}: {e}", case.name));
        out.extend(host(&logits));
    }
    assert_eq!(
        out.len(),
        VOCAB as usize * (1 + DECODE_STEPS.len()),
        "{}: one [1, vocab] row per step",
        case.name
    );
    assert!(
        out.iter().all(|x| x.is_finite()),
        "{}: non-finite logits",
        case.name
    );
    out
}

/// How far a logit may move between two runs of the same MLX graph before it counts as a change.
///
/// Applies to the six fused-SDPA architectures only (see the precision contract). Absolute rather
/// than relative because the drift tracks the largest intermediates, not each value's own
/// magnitude. A 1% attention-scale change moves llama's logits by 7.8e-3, so real changes stay
/// outside it; the eager-`bmm` architectures drift by about that much on their own, which is why
/// they are excluded rather than accommodated.
const FORWARD_ABS_TOL: f32 = 4e-3;

fn host(a: &Array) -> Vec<f32> {
    a.as_dtype(Dtype::Float32)
        .unwrap()
        .as_slice::<f32>()
        .to_vec()
}

/// **The regression gate.** Every architecture's full forward output, as the base branch produced
/// it — matched within the Metal band (see the precision contract above) — plus the coverage check
/// that the case list is exactly the generic-decoder architecture set.
///
/// Deliberately a **single** test: a second `#[test]` in this binary runs on a second thread, and
/// building its cases would touch MLX concurrently with this one's forward passes. That is exactly
/// the kind of contention the precision contract above is about, and there is no reason to invite
/// it inside our own test binary.
#[test]
fn every_architecture_forward_matches_the_base_branch() {
    let cases = cases();
    assert_case_coverage(&cases);

    if std::env::var("SC18769_WRITE_FORWARD_GOLDEN").is_ok() {
        let mut doc = Map::new();
        doc.insert(
            "_note".into(),
            Value::String(
                "Generated by `SC18769_WRITE_FORWARD_GOLDEN=1 cargo test -p mlx-llm --test \
                 architecture_forward`. Captured on origin/feature/sc-18755-ltx-2-5 so the values \
                 predate sc-18769's changes to the shared ModelConfig and decoder."
                    .into(),
            ),
        );
        for case in &cases {
            let values: Vec<Value> = run_forward(case)
                .into_iter()
                .map(|x| json!(x as f64))
                .collect();
            doc.insert(case.name.into(), Value::Array(values));
        }
        let path = golden_path();
        std::fs::create_dir_all(path.parent().unwrap()).unwrap();
        std::fs::write(&path, serde_json::to_string_pretty(&doc).unwrap() + "\n").unwrap();
        eprintln!("wrote {}", path.display());
        return;
    }

    let text = std::fs::read_to_string(golden_path()).expect("forward goldens must be committed");
    let golden: Value = serde_json::from_str(&text).expect("parse forward goldens");
    let mut pinned = 0;
    for case in &cases {
        let want: Vec<f32> = golden[case.name]
            .as_array()
            .unwrap_or_else(|| panic!("{}: missing from the forward goldens", case.name))
            .iter()
            .map(|x| x.as_f64().unwrap() as f32)
            .collect();
        // Always run it: shape, finiteness and cache growth are asserted inside `run_forward`, and
        // they are worth checking on every architecture regardless of kernel reproducibility.
        let got = run_forward(case);
        assert_eq!(got.len(), want.len(), "{}: logit count", case.name);
        if !case.numerics_pinned {
            continue;
        }
        pinned += 1;
        if let Some((i, (g, w))) = got
            .iter()
            .zip(&want)
            .enumerate()
            .find(|(_, (g, w))| (*g - *w).abs() > FORWARD_ABS_TOL)
        {
            panic!(
                "{name}: forward output moved at index {i} by {delta} (got {g}, the base branch \
                 produced {w}) — beyond the {tol} Metal reproducibility band. The shared decoder \
                 or config changed this architecture's numerics.",
                name = case.name,
                delta = (g - w).abs(),
                tol = FORWARD_ABS_TOL,
            );
        }
    }
    assert_eq!(
        pinned, 6,
        "six fused-SDPA architectures must have their numerics pinned here; the other two are \
         pinned by the candle mirror"
    );
}

/// The case list must cover **every** architecture the generic decoder serves, so a newly-added one
/// cannot land without a forward golden.
fn assert_case_coverage(cases: &[Case]) {
    let covered: std::collections::BTreeSet<&str> = cases.iter().map(|c| c.family).collect();
    let expected: std::collections::BTreeSet<&str> = [
        "llama",
        "qwen3",
        "phi3",
        "qwen2_moe",
        "gemma2",
        "glm4",
        "deepseek_v2",
        "qwen3_vl",
    ]
    .into_iter()
    .collect();
    assert_eq!(
        covered, expected,
        "the forward suite must cover exactly the generic-decoder architectures"
    );
}
