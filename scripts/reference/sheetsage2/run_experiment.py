def _environment() -> dict:
    import torch
    import transformers

    return {
        "python": sys.version.split()[0], "torch": torch.__version__,
        "transformers": transformers.__version__, "platform": platform.platform(),
        "machine": platform.machine(), "torch_threads": torch.get_num_threads(),
        "mps_available": bool(getattr(torch.backends, "mps", None) and torch.backends.mps.is_available()),
        "ffmpeg": subprocess.run(["ffmpeg", "-version"], capture_output=True, text=True,
                                 encoding="utf-8").stdout.splitlines()[0],
    }


def _load(local_files_only: bool, path: str | None = None, revision: str = SHEETSAGE2_REVISION):
    from transformers import AutoModel

    started = time.monotonic()
    if path is None:
        model = AutoModel.from_pretrained(
            SHEETSAGE2_REPO, revision=revision, code_revision=revision,
            trust_remote_code=True, local_files_only=local_files_only)
    else:
        model = AutoModel.from_pretrained(path, trust_remote_code=True, local_files_only=True)
    model = model.eval().to("cpu")
    devices = {p.device.type for p in model.parameters()}
    if devices != {"cpu"}:
        raise SystemExit(f"CPU-only lane violated: parameters on {devices}")
    if path is None:
        cfg = model.config
        if (cfg.base_model_revision, cfg.base_model_sha256) != (MERT_REVISION, MERT_SHA256):
            raise SystemExit("SheetSage2 config does not pin the expected MERT-v2-FullSong parent")
    params = sum(p.numel() for p in model.parameters())
    return model, {"load_seconds": round(time.monotonic() - started, 2), "parameters": params,
                   "dtype": str(next(model.parameters()).dtype), "device": "cpu",
                   "snapshot": str(getattr(model, "_source_snapshot", path))}


def _summary(result: dict) -> dict:
    keys = ("duration_seconds", "prompts", "preset", "melody_only", "dtype", "window_seconds",
            "overlap_seconds", "lookahead_seconds", "elapsed_seconds", "warnings", "melody_notes",
            "vocal_notes", "instrumental_notes", "abc_measures", "abc_error", "diagnostics",
            "render_error")
    out = {k: result.get(k) for k in keys if k in result}
    out["windows"] = [{k: w[k] for k in ("start", "end", "tokens", "events", "accepted_events",
                                          "elapsed_seconds") if k in w}
                      for w in result.get("windows", [])]
    rendered = result.get("rendered")
    if isinstance(rendered, dict):
        out["rendered"] = rendered
    return out


def run_case(name: str, work: Path, threads: int) -> None:
    import torch

    torch.set_num_threads(threads)
    spec = CASES[name]
    fixtures = json.loads((work / "fixtures" / "fixtures.json").read_text(encoding="utf-8"))
    out_dir = work / "cases" / name
    if out_dir.exists():
        shutil.rmtree(out_dir)
    out_dir.mkdir(parents=True)
    report = {"case": name, "spec": spec, "environment": _environment()}
    if not spec.get("online"):
        os.environ["HF_HUB_OFFLINE"] = "1"
    report["hf_hub_offline"] = os.environ.get("HF_HUB_OFFLINE") == "1"

    if name == "render_only":
        source = work / "cases" / "real_full"
        snapshot = json.loads((source / "case.json").read_text(encoding="utf-8"))["load"]["snapshot"]
        started = time.monotonic()
        proc = subprocess.run(
            [sys.executable, str(Path(snapshot) / "render.py"), "--input", str(source / "output"),
             "--output", str(out_dir / "output"), "--audio", "--score", "svg",
             "--parts", "vocal,instrumental,chords"],
            capture_output=True, text=True, encoding="utf-8")
        report.update(returncode=proc.returncode, stdout=proc.stdout[-4000:], stderr=proc.stderr[-4000:],
                      wall_seconds=round(time.monotonic() - started, 2))
        write_json(out_dir / "case.json", report)
        return

    model, report["load"] = _load(local_files_only=not spec.get("online"),
                                  revision=spec.get("revision", SHEETSAGE2_REVISION))
    report["load"]["revision"] = spec.get("revision", SHEETSAGE2_REVISION)
    kwargs = dict(dtype="fp32", preset="default")
    for key in ("melody_only", "render_audio", "render_score", "export_embeddings",
                "export_logits", "export_scores"):
        if key in spec:
            kwargs[key] = spec[key]

    if name == "failures":
        report["probes"] = _failure_probes(model, work, fixtures)
        write_json(out_dir / "case.json", report)
        return

    fixture = fixtures[spec["fixture"]]
    if spec["fixture"] == "nav_ssb":
        kwargs["max_seconds"] = fixture["max_seconds"]
    if spec.get("merged"):
        merged = work / "merged-snapshot"
        started = time.monotonic()
        if merged.exists():
            shutil.rmtree(merged)
        model.save_pretrained(merged)
        report["save_merged_seconds"] = round(time.monotonic() - started, 2)
        report["merged_files"] = {p.name: p.stat().st_size for p in sorted(merged.iterdir()) if p.is_file()}
        del model
        import gc
        gc.collect()
        model, report["merged_load"] = _load(local_files_only=True, path=str(merged))
    started = time.monotonic()
    result = model.transcribe(fixture["path"], output_dir=str(out_dir / "output"), **kwargs)
    report["transcribe_seconds"] = round(time.monotonic() - started, 2)
    report["result"] = _summary(result)
    if spec.get("export_embeddings"):
        # Encoder cost alone: every window is padded to the fixed 300 s context before MERT2.
        sys.path.insert(0, str(Path(model._source_snapshot)))
        from audio_sheetsage2 import load_audio

        waveform = load_audio(fixture["path"])[None]
        timings = []
        with torch.inference_mode():
            for _ in range(2):
                tick = time.monotonic()
                memory = model.encode(waveform)
                timings.append(round(time.monotonic() - tick, 2))
        report["encoder_only"] = {"seconds_per_300s_window": timings, "memory_shape": list(memory.shape)}
        from safetensors import safe_open

        shapes = {}
        for path in sorted((out_dir / "output" / "tensors").rglob("*.safetensors")):
            with safe_open(str(path), "pt") as handle:
                shapes[str(path.relative_to(out_dir / "output"))] = {
                    key: list(handle.get_slice(key).get_shape()) for key in handle.keys()}
        report["tensor_shapes"] = {k: v for k, v in shapes.items() if "audio" in k or k.endswith("0000.safetensors")}
        report["tensor_files"] = len(shapes)
    write_json(out_dir / "case.json", report)


def _failure_probes(model, work: Path, fixtures: dict) -> list:
    import numpy as np

    sys.path.insert(0, str(Path(model._source_snapshot)))
    probes = []

    def probe(label, fn):
        started = time.monotonic()
        entry = {"probe": label}
        try:
            value = fn()
            entry.update(outcome="returned", value=value)
        except Exception as exc:  # noqa: BLE001 - failure modes are the point of this probe
            entry.update(outcome="raised", type=type(exc).__name__, error=str(exc)[:600])
            partial = getattr(exc, "result", None)
            if isinstance(partial, dict):
                entry["partial_result"] = _summary(partial)
        entry["seconds"] = round(time.monotonic() - started, 2)
        probes.append(entry)

    silence = np.zeros(24000 * 12, dtype=np.float32)
    probe("array shorter than 1025 samples",
          lambda: _summary(model.transcribe(np.zeros(1000, np.float32), sampling_rate=24000, dtype="fp32")))
    probe("non-finite waveform",
          lambda: _summary(model.transcribe(np.full(48000, np.nan, np.float32), sampling_rate=24000, dtype="fp32")))
    probe("array without sampling_rate",
          lambda: _summary(model.transcribe(silence, dtype="fp32")))
    probe("undecodable bytes",
          lambda: _summary(model.transcribe(b"not audio at all" * 64, dtype="fp32")))
    probe("12 s digital silence, full",
          lambda: _summary(model.transcribe(silence, sampling_rate=24000, dtype="fp32")))
    probe("12 s digital silence, melody_only",
          lambda: _summary(model.transcribe(silence, sampling_rate=24000, dtype="fp32", melody_only=True)))

    def paper_decode():
        from audio_sheetsage2 import load_audio  # the snapshot's own decoder (torchaudio/FFmpeg libs)

        return {"samples": int(load_audio(fixtures["nav_ssb"]["path"], preset="paper").numel())}

    probe("preset=paper decode via torchaudio FFmpeg backend", paper_decode)
    return probes


