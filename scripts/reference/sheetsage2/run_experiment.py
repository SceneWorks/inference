def _tree_rss_kib(root: int) -> int:
    listing = subprocess.run(["ps", "-A", "-o", "pid=,ppid=,rss="], capture_output=True, text=True,
                             encoding="utf-8").stdout
    children, rss = {}, {}
    for line in listing.splitlines():
        parts = line.split()
        if len(parts) == 3:
            pid, ppid, kib = map(int, parts)
            children.setdefault(ppid, []).append(pid)
            rss[pid] = kib
    total, stack = 0, [root]
    while stack:
        pid = stack.pop()
        total += rss.get(pid, 0)
        stack.extend(children.get(pid, []))
    return total


def drive_case(name: str, work: Path, threads: int, cap_gb: float, timeout: float) -> dict:
    log = work / "cases" / f"{name}.log"
    log.parent.mkdir(parents=True, exist_ok=True)
    command = [sys.executable, str(Path(__file__).resolve()), "case", name, "--work", str(work),
               "--threads", str(threads)]
    env = dict(os.environ, PYTORCH_ENABLE_MPS_FALLBACK="0", CUDA_VISIBLE_DEVICES="")
    started, peak, killed = time.monotonic(), 0, None
    with log.open("wb") as handle:
        proc = subprocess.Popen(command, stdout=handle, stderr=subprocess.STDOUT, env=env,
                                start_new_session=True)
        while proc.poll() is None:
            peak = max(peak, _tree_rss_kib(proc.pid))
            elapsed = time.monotonic() - started
            if peak > cap_gb * 1024 * 1024 or elapsed > timeout:
                killed = "rss-cap" if peak > cap_gb * 1024 * 1024 else "timeout"
                os.killpg(proc.pid, signal.SIGTERM)
                proc.wait(30)
                break
            time.sleep(0.5)
    measured = {"case": name, "returncode": proc.returncode, "wall_seconds": round(time.monotonic() - started, 1),
                "peak_tree_rss_gib": round(peak / 1024 / 1024, 2), "killed": killed,
                "rss_sampling": "ps -A rss of the child process tree every 0.5 s",
                "log": str(log)}
    print(json.dumps(measured), flush=True)
    return measured


def evaluate(work: Path) -> dict:
    """Score the synthetic fixture's transcription against its exact ground truth."""
    import mir_eval
    import numpy as np

    report = {}
    for case in ("synth_full", "synth_merged", "synth_eb_release", "synth_eb_head"):
        truth_name = "synth_eb_truth.json" if case.startswith("synth_eb") else "synth_truth.json"
        truth = json.loads((work / "fixtures" / truth_name).read_text(encoding="utf-8"))
        out = work / "cases" / case / "output"
        if not (out / "melody_full.lab").is_file():
            continue

        def rows(name):
            path = out / name
            if not path.is_file():
                return []
            return [line.split("\t") for line in path.read_text(encoding="utf-8").splitlines() if line.strip()]

        ref = np.array([[a, b] for a, b, _ in truth["melody_notes"]], dtype=float)
        ref_p = np.array([p for _, _, p in truth["melody_notes"]], dtype=float)
        est_rows = rows("melody_full.lab")
        est = np.array([[float(r[0]), float(r[1])] for r in est_rows], dtype=float).reshape(-1, 2)
        est_p = np.array([float(r[2]) for r in est_rows], dtype=float)

        def f1(ref_pitch, est_pitch, onset=0.05):
            if not len(est):
                return {"precision": 0.0, "recall": 0.0, "f1": 0.0}
            p, r, f, _ = mir_eval.transcription.precision_recall_f1_overlap(
                ref, mir_eval.util.midi_to_hz(ref_pitch), est, mir_eval.util.midi_to_hz(est_pitch),
                onset_tolerance=onset, pitch_tolerance=50.0, offset_ratio=None)
            return {"precision": round(p, 4), "recall": round(r, 4), "f1": round(f, 4)}

        chroma = lambda values: 60 + np.mod(values, 12)  # noqa: E731
        melody = {"reference_notes": len(ref), "estimated_notes": len(est),
                  "vocal_notes": sum(r[3] == "0" for r in est_rows),
                  "instrumental_notes": sum(r[3] == "1" for r in est_rows),
                  "onset50ms_exact_pitch": f1(ref_p, est_p),
                  "onset50ms_pitch_class": f1(chroma(ref_p), chroma(est_p)),
                  "onset100ms_pitch_class": f1(chroma(ref_p), chroma(est_p), 0.1)}
        chord_rows = [r for r in rows("chord.lab") if len(r) >= 3]
        chords = {}
        if chord_rows:
            ref_int = np.array([[a, b] for a, b, _ in truth["chords"]], dtype=float)
            est_int = np.array([[float(r[0]), float(r[1])] for r in chord_rows], dtype=float)
            scores = mir_eval.chord.evaluate(ref_int, [c for _, _, c in truth["chords"]],
                                             est_int, [r[2] for r in chord_rows])
            chords = {k: round(float(scores[k]), 4) for k in ("root", "majmin", "thirds", "mirex")}
            chords["estimated_labels"] = [r[2] for r in chord_rows]
        beat_rows = rows("beat.lab")
        est_beats = np.array([float(r[0]) for r in beat_rows], dtype=float)
        est_down = np.array([float(r[0]) for r in rows("downbeat.lab")], dtype=float)
        beats = {
            "f_measure": round(float(mir_eval.beat.f_measure(
                mir_eval.beat.trim_beats(np.array(truth["beats"])), mir_eval.beat.trim_beats(est_beats))), 4),
            "downbeat_f_measure": round(float(mir_eval.beat.f_measure(
                mir_eval.beat.trim_beats(np.array(truth["downbeats"])), mir_eval.beat.trim_beats(est_down))), 4),
            "estimated_bpm": round(60.0 / float(np.median(np.diff(est_beats))), 2) if len(est_beats) > 1 else None,
            "estimated_meters": sorted({f"{r[2]}/{r[3]}" for r in beat_rows if len(r) >= 4}),
        }
        key_rows = [r for r in rows("key.lab") if len(r) >= 3]
        report[case] = {"melody": melody, "chords": chords, "beats": beats,
                        "keys": [r[2] for r in key_rows], "reference_key": truth["key"]}
    for case in ("synth_full", "synth_merged", "synth_eb_release", "synth_eb_head", "real_full",
                 "real_melody", "real_full_head"):
        path = work / "cases" / case / "output" / "tokens.json"
        if path.is_file():
            # Hash only the token IDs: tokens.json also records per-window wall time.
            ids = [window["tokens"] for window in json.loads(path.read_text(encoding="utf-8"))]
            report.setdefault("token_identity", {})[case] = hashlib.sha256(
                json.dumps(ids).encode("utf-8")).hexdigest()
    ident = report.get("token_identity", {})

    def same(a, b):
        return ident[a] == ident[b] if a in ident and b in ident else None

    report["merged_snapshot_reproduces_adapter_load_tokens"] = same("synth_full", "synth_merged")
    report["head_code_reproduces_release_tokens"] = {
        "real": same("real_full", "real_full_head"), "synth_eb": same("synth_eb_release", "synth_eb_head")}
    report["melody_only_changes_tokens"] = (not same("real_full", "real_melody")) \
        if same("real_full", "real_melody") is not None else None
    eb = {}
    for case in ("synth_eb_release", "synth_eb_head"):
        out = work / "cases" / case / "output"
        if (out / "score.abc").is_file():
            import re

            abc = (out / "score.abc").read_text(encoding="utf-8")
            eb[case] = {"key_header": next((l for l in abc.splitlines() if l.startswith("K:")), None),
                        "abc_chord_symbols": sorted(set(re.findall(r'"([^"]*)"', without_chords_header(abc))))}
    if eb:
        report["eb_spelling"] = eb
    report["real_clip"] = real_clip_checks(work)
    write_json(work / "evaluation.json", report)
    write_json(ARTIFACTS / "evaluation.json", report)
    return report


def real_clip_checks(work: Path) -> dict:
    """Relations between the real-clip cases (no ground truth exists for the recording)."""
    import re

    def text(case, name):
        path = work / "cases" / case / "output" / name
        return path.read_text(encoding="utf-8") if path.is_file() else None

    def without_chords(abc):
        # Chord symbols are quoted strings in music lines; header/voice lines keep their quotes.
        return "\n".join(line if re.match(r"^[A-Za-z]:", line) else re.sub(r'"[^"]*"', "", line)
                         for line in abc.splitlines())

    out = {}
    full, melody, head = (text(c, "score.abc") for c in ("real_full", "real_melody", "real_full_head"))
    if full and melody:
        out["melody_only_equals_full_without_chord_symbols"] = without_chords(full) == melody
        out["melody_only_has_chord_symbols"] = without_chords(melody) != melody
    if full and head:
        out["head_revision_abc_identical"] = full == head
        out["head_revision_notes_identical"] = without_chords(full) == without_chords(head)
        out["release_chord_symbols"] = re.findall(r'"([^"]*)"', without_chords_header(full))
        out["head_chord_symbols"] = re.findall(r'"([^"]*)"', without_chords_header(head))
        out["chord_lab_identical"] = text("real_full", "chord.lab") == text("real_full_head", "chord.lab")
        out["head_chord_lab"] = sorted({line.split("\t")[2] for line in
                                        (text("real_full_head", "chord.lab") or "").splitlines()
                                        if line.count("\t") >= 2})
        out["release_chord_lab"] = sorted({line.split("\t")[2] for line in
                                           (text("real_full", "chord.lab") or "").splitlines()
                                           if line.count("\t") >= 2})
    return out


def without_chords_header(abc: str) -> str:
    """Music lines only (drop header and voice-definition lines)."""
    import re

    return "\n".join(line for line in abc.splitlines() if not re.match(r"^[A-Za-z]:", line))


def collect(work: Path, measurements: list) -> None:
    """Copy small reviewable outputs (never weights, tensors or audio) into artifacts/."""
    for name in CASES:
        case_dir = work / "cases" / name
        if not case_dir.is_dir():
            continue
        target = ARTIFACTS / name
        if target.exists():
            shutil.rmtree(target)
        target.mkdir(parents=True)
        report = json.loads((case_dir / "case.json").read_text(encoding="utf-8")) \
            if (case_dir / "case.json").is_file() else {}
        _scrub(report, work)
        write_json(target / "case.json", report)
        skipped = {}
        out = case_dir / "output"
        only = DUPLICATE_CASE_FILES if name in DUPLICATE_CASES else None
        for path in sorted(out.rglob("*")) if out.is_dir() else []:
            rel = path.relative_to(out)
            if not path.is_file() or rel.parts[0] == "tensors":
                continue
            keep = path.suffix in COLLECT_SUFFIXES and path.stat().st_size <= COLLECT_MAX_BYTES
            if path.suffix == ".png" and not rel.name.endswith("_001.png"):
                keep = False
            if only is not None and str(rel) not in only:
                keep = False
            if not keep:
                skipped[str(rel)] = path.stat().st_size
                continue
            (target / rel).parent.mkdir(parents=True, exist_ok=True)
            if path.suffix in (".mid", ".png"):
                shutil.copy2(path, target / rel)
            else:
                (target / rel).write_text(_scrub(path.read_text(encoding="utf-8"), work), encoding="utf-8")
        if skipped:
            write_json(target / "not_committed.json", {
                "reason": "size/type policy (weights, tensors, audio and large files stay in --work); "
                          "duplicate cases keep only the files that differ in kind",
                "files": skipped})
        log = work / "cases" / f"{name}.log"
        text = log.read_text(encoding="utf-8", errors="replace").strip() if log.is_file() else ""
        if text:
            tail = "\n".join(text.splitlines()[-80:])
            (target / "run.log").write_text(_scrub(tail, work) + "\n", encoding="utf-8")
    write_json(ARTIFACTS / "measurements.json", {
        "machine": {"model": _sysctl("hw.model"), "cpu": _sysctl("machdep.cpu.brand_string"),
                    "logical_cpus": _sysctl("hw.ncpu"),
                    "memory_gib": round(int(_sysctl("hw.memsize") or 0) / 2**30, 1),
                    "os": platform.platform()},
        "note": "Observations on this one machine, torch CPU device, fp32. Not portable requirements.",
        "cases": [{k: v for k, v in m.items() if k != "log"} for m in measurements],
    })


def _sysctl(name: str) -> str:
    try:
        return subprocess.run(["sysctl", "-n", name], capture_output=True, text=True,
                              encoding="utf-8").stdout.strip()
    except OSError:
        return ""


def _scrub(value, work: Path):
    """Replace machine-local paths in committed JSON with $WORK/$HF placeholders."""
    if isinstance(value, dict):
        for key in list(value):
            value[key] = _scrub(value[key], work)
        return value
    if isinstance(value, list):
        return [_scrub(v, work) for v in value]
    if isinstance(value, str):
        hub = os.environ.get("HF_HUB_CACHE") or str(Path(os.environ.get("HF_HOME", Path.home() / ".cache/huggingface")) / "hub")
        return value.replace(str(work), "$WORK").replace(hub, "$HF_HUB_CACHE").replace(str(Path.home()), "~")
    return value


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("command", choices=("fixtures", "run", "case", "evaluate", "collect", "all"))
    parser.add_argument("name", nargs="?", help="case name for 'case'/'run' (default: all cases)")
    parser.add_argument("--work", type=Path, required=True, help="scratch directory OUTSIDE the repository")
    parser.add_argument("--threads", type=int, default=8)
    parser.add_argument("--rss-cap-gb", type=float, default=24.0)
    parser.add_argument("--timeout", type=float, default=3600.0, help="per case, seconds")
    args = parser.parse_args()
    work = args.work.resolve()
    if work == HERE.parents[2] or HERE.parents[2] in work.parents:
        parser.error("--work must be outside the repository (weights, tensors and audio land there)")
    work.mkdir(parents=True, exist_ok=True)
    if args.command == "case":
        run_case(args.name, work, args.threads)
        return 0
    if args.command in ("fixtures", "all"):
        fetch_fixtures(work)
    measurements = []
    if args.command in ("run", "all"):
        names = [args.name] if args.name else list(CASES)
        for name in names:
            measurements.append(drive_case(name, work, args.threads, args.rss_cap_gb, args.timeout))
        previous = work / "measurements.json"
        merged = {m["case"]: m for m in (json.loads(previous.read_text(encoding="utf-8"))
                                         if previous.is_file() else [])}
        merged.update({m["case"]: m for m in measurements})
        measurements = [merged[n] for n in CASES if n in merged]
        write_json(previous, measurements)
    if args.command in ("evaluate", "all"):
        print(json.dumps(evaluate(work), indent=2))
    if args.command in ("collect", "all"):
        previous = work / "measurements.json"
        measurements = json.loads(previous.read_text(encoding="utf-8")) if previous.is_file() else []
        collect(work, measurements)
    return 0


if __name__ == "__main__":
    sys.exit(main())
