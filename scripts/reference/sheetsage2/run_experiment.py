def synth_fixture(path: Path, truth_path: Path, transpose: int = 0) -> None:
    """Deterministic lead sheet: melody, triads, bass, kick/snare/hat, 100 BPM 4/4.

    C major by default; ``transpose`` shifts every pitch (labels spelled with flats), which is how
    the Eb-major fixture exercises key-aware chord spelling.
    """
    import numpy as np

    rng = np.random.default_rng(23003)
    beat = 60.0 / SYNTH_BPM
    bars = len(SYNTH_CHORDS)
    total = bars * 4 * beat + 1.0
    out = np.zeros(int(total * SYNTH_RATE), dtype=np.float64)

    def hz(midi):
        return 440.0 * 2 ** ((midi - 69) / 12)

    def tone(midi, start, dur, amp, harmonics, power, vibrato=0.0):
        n = int(dur * SYNTH_RATE)
        t = np.arange(n) / SYNTH_RATE
        phase_f = hz(midi) * (1 + vibrato * np.sin(2 * np.pi * 5.0 * t))
        phase = 2 * np.pi * np.cumsum(phase_f) / SYNTH_RATE
        wave_ = sum(np.sin(k * phase) / k ** power for k in range(1, harmonics + 1))
        env = np.minimum(1, t / 0.015) * np.minimum(1, (dur - t) / 0.05).clip(0) * np.exp(-t * 0.6)
        i = int(start * SYNTH_RATE)
        out[i:i + n] += amp * wave_ * env

    notes, chords = [], []
    for bar, (label, melody) in enumerate(zip(SYNTH_CHORDS, SYNTH_MELODY)):
        bar_start = bar * 4 * beat
        root, quality = label.split(":")
        base = CHORD_ROOTS[root] + transpose
        label = f"{FLAT_NAMES[base % 12]}:{quality}"
        triad = [base, base + (4 if quality == "maj" else 3), base + 7]
        for pitch in triad:
            tone(pitch, bar_start, 4 * beat, 0.07, 4, 1.5)
        tone(base - 12, bar_start, 4 * beat, 0.12, 3, 1.0)
        chords.append([round(bar_start, 6), round(bar_start + 4 * beat, 6), label])
        for offset, length, pitch in melody:
            pitch += transpose
            start = bar_start + offset * beat
            dur = length * beat * 0.9
            tone(pitch, start, dur, 0.28, 6, 1.0, vibrato=0.003)
            notes.append([round(start, 6), round(start + dur, 6), pitch])
        for b in range(4):
            t0 = bar_start + b * beat
            i = int(t0 * SYNTH_RATE)
            if b in (0, 2):
                n = int(0.15 * SYNTH_RATE)
                t = np.arange(n) / SYNTH_RATE
                f = 50 + 70 * np.exp(-t * 30)
                out[i:i + n] += 0.5 * np.sin(2 * np.pi * np.cumsum(f) / SYNTH_RATE) * np.exp(-t * 25)
            else:
                n = int(0.12 * SYNTH_RATE)
                out[i:i + n] += 0.18 * rng.standard_normal(n) * np.exp(-np.arange(n) / SYNTH_RATE * 35)
            for half in (0, 0.5):
                j = int((t0 + half * beat) * SYNTH_RATE)
                n = int(0.03 * SYNTH_RATE)
                hat = np.diff(rng.standard_normal(n + 1))
                out[j:j + n] += 0.04 * hat * np.exp(-np.arange(n) / SYNTH_RATE * 120)
    out *= 0.9 / np.abs(out).max()
    pcm = (out * 32767).astype("<i2")
    stereo = np.stack([pcm, pcm], axis=1).tobytes()
    path.parent.mkdir(parents=True, exist_ok=True)
    with wave.open(str(path), mode="wb") as handle:
        handle.setnchannels(2)
        handle.setsampwidth(2)
        handle.setframerate(SYNTH_RATE)
        handle.writeframes(stereo)
    beats = [round(i * beat, 6) for i in range(bars * 4)]
    write_json(truth_path, {
        "generator": "scripts/reference/sheetsage2/run_experiment.py synth_fixture (seed 23003)",
        "sample_rate": SYNTH_RATE, "channels": 2, "duration_seconds": round(total, 6),
        "tempo_bpm": SYNTH_BPM, "meter": [4, 4], "key": f"{FLAT_NAMES[transpose % 12]}:maj",
        "transpose_semitones": transpose,
        "beats": beats, "downbeats": beats[::4], "chords": chords, "melody_notes": notes,
        "wav_sha256": sha256(path),
    })


def fetch_fixtures(work: Path) -> dict:
    fixtures = work / "fixtures"
    fixtures.mkdir(parents=True, exist_ok=True)
    real = fixtures / NAV_SSB["name"]
    if not real.is_file() or sha1(real) != NAV_SSB["sha1"]:
        request = urllib.request.Request(NAV_SSB["url"], headers={
            "User-Agent": "SceneWorks-inference-sc-23003-reference/1.0"})
        with urllib.request.urlopen(request, timeout=120) as response, real.open("wb") as handle:
            shutil.copyfileobj(response, handle)
    if sha1(real) != NAV_SSB["sha1"] or real.stat().st_size != NAV_SSB["bytes"]:
        raise SystemExit(f"{real}: SHA-1/size mismatch with the Commons-published digest")
    synth = fixtures / "synth.wav"
    truth = fixtures / "synth_truth.json"
    synth_fixture(synth, truth)
    synth_eb = fixtures / "synth_eb.wav"
    truth_eb = fixtures / "synth_eb_truth.json"
    synth_fixture(synth_eb, truth_eb, transpose=3)
    manifest = {
        "nav_ssb": dict(NAV_SSB, path=str(real), sha256=sha256(real)),
        "synth": {"path": str(synth), "truth": str(truth), "sha256": sha256(synth),
                  "license": "Generated by this script; no third-party material."},
        "synth_eb": {"path": str(synth_eb), "truth": str(truth_eb), "sha256": sha256(synth_eb),
                     "license": "Generated by this script (synth transposed +3 to Eb major)."},
    }
    write_json(fixtures / "fixtures.json", manifest)
    write_json(ARTIFACTS / "fixtures.json", {
        name: {k: v for k, v in entry.items() if k not in ("path", "truth")}
        for name, entry in manifest.items()})
    shutil.copy2(truth, ARTIFACTS / "synth_truth.json")
    shutil.copy2(truth_eb, ARTIFACTS / "synth_eb_truth.json")
    return manifest


